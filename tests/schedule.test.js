const S = require('../site/shared/schedule.js'), assert = require('assert');
assert.deepEqual(S.parseRange('4pm-10pm'), { start: '16:00', end: '22:00' });
assert.deepEqual(S.parseRange('4pm-12am'), { start: '16:00', end: '24:00' });
assert.deepEqual(S.parseRange('4-10pm'), { start: '16:00', end: '22:00' });
assert.deepEqual(S.parseRange('10am to 6:30 pm'), { start: '10:00', end: '18:30' });
assert.deepEqual(S.parseRange('10-2pm'), { start: '10:00', end: '14:00' });
assert.equal(S.parseRange('October 21-24, 2026'), null);
assert.equal(S.parseRange('no later than 10:00 pm'), null);
const txt = 'October 21-24, 2026\nWednesday and Thursday 4pm-10pm,\nFriday and Saturday 4pm-12am\n(Will adjust to your needs with prior notice)\nTimes for 2027 and 2028 to be determined by June of those years.';
const rules = S.parseRules(txt);
assert.deepEqual(rules, [{ days: [3, 4], start: '16:00', end: '22:00' }, { days: [5, 6], start: '16:00', end: '24:00' }]);
const sch = S.build(rules, '2026-10-21', '2026-10-24');
assert.deepEqual(sch.map(x => x.date + ' ' + x.start + '-' + x.end), ['2026-10-21 16:00-22:00', '2026-10-22 16:00-22:00', '2026-10-23 16:00-24:00', '2026-10-24 16:00-24:00']);
assert.equal(S.format(sch), 'Wed–Thu 4pm–10pm · Fri–Sat 4pm–12am');
assert.deepEqual(S.fromLines(S.toLines(sch)), sch);
const all = S.build(S.parseRules('Daily 10am-6pm'), '2027-03-01', '2027-03-03'); assert.equal(all.length, 3); assert.equal(S.format(all), 'Mon–Wed 10am–6pm');
assert.equal(S.parseRules('Wed-Sat 5pm-11pm')[0].days.join(), '3,4,5,6');
assert.equal(S.parseRules('From open times provided and no later than 10:00 pm').length, 0);
assert.equal(S.fmtTime('13:30'), '1:30pm'); assert.equal(S.fmtTime('00:00'), '12am');
console.log('schedule ok');
